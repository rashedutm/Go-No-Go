"""Builds web_shell/loading_shell.html (the browser loading page) from the template.
Embeds small subsets of the game's fonts as base64 so the loader shows the right letters at once.
Run from the project folder:  python tools/build_web_shell.py   (needs: pip install fonttools)
Written with AI assistance (Space Apps 2026)."""
import base64, io, string
from fontTools import subset


def font_b64(path, text):
    opts = subset.Options()
    f = subset.load_font(path, opts)
    s = subset.Subsetter(opts)
    s.populate(text=text)
    s.subset(f)
    b = io.BytesIO()
    subset.save_font(f, b, opts)
    return base64.b64encode(b.getvalue()).decode()


t = open('web_shell/loading_shell.template.html', encoding='utf-8').read()
t = t.replace('Generated by tools/build_web_shell.py; edit the template there, not this file.',
              'Generated by tools/build_web_shell.py from loading_shell.template.html. Fonts: subsets of Barlow Condensed and IBM Plex Mono (SIL OFL).')
t = t.replace('__DISP__', font_b64('ui/fonts/BarlowCondensed-ExtraBold.ttf', 'GONO-/'))
t = t.replace('__MONO__', font_b64('ui/fonts/IBMPlexMono-Medium.ttf', string.ascii_uppercase + string.digits + ' %.·!?-:/'))
open('web_shell/loading_shell.html', 'w', encoding='utf-8', newline='\n').write(t)
print('wrote web_shell/loading_shell.html')
